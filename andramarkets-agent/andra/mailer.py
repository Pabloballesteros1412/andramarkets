"""SMTP delivery.

The email arrives ready to publish: the caption sits at the top in plain text
so it can be selected in one go, the pre-flight checks sit under it, and the
assets are attached.
"""
from __future__ import annotations

import mimetypes
import os
import smtplib
from email.message import EmailMessage
from pathlib import Path

TEMPLATE = """{li_caption}

====================================================================
TIKTOK CAPTION
{tt_caption}

TIKTOK VOICEOVER SCRIPT
{tt_script}

====================================================================
PRE-FLIGHT
LinkedIn caption: {characters} / 3,000 chars{limit_flag}
Visible before "see more": {hook}
Hashtags: {hashtags}   Figure check: {audit}
Style flags: {style_flags}
Risk score: {score} ({label})   Series with no print: {missing}

ATTACHMENTS
1. Research note, A4, 5 pages.
2. LinkedIn carousel, 8 pages. Upload as a Document post.
3. TikTok stills, {tiktok_count} PNGs at 1080x1920. Upload as a photo post.

PUBLISHING
LinkedIn: Create post > Document > upload the carousel > paste the caption.
TikTok:   Upload > Photo > add the PNGs in order > paste the caption.
====================================================================
Generated by the Andra Markets close agent."""


def send(li_caption: str, tt_caption: str, tt_script: str, checks: dict,
         attachments: list[str], ctx: dict, audit_ok: bool = True,
         missing: int = 0, tiktok_count: int = 0) -> None:
    host = os.getenv("SMTP_HOST", "smtp.gmail.com")
    port = int(os.getenv("SMTP_PORT", "465"))
    user = os.environ["SMTP_USER"]
    pwd = os.environ["SMTP_PASSWORD"]
    to = [a.strip() for a in os.environ["MAIL_TO"].split(",") if a.strip()]

    flag = "" if audit_ok else " [REVIEW: figure check]"
    msg = EmailMessage()
    msg["Subject"] = (f"Andra Markets / {ctx['date_short']} / "
                      f"{ctx['n'].get('headline', 'Daily close')[:70]}{flag}")
    msg["From"] = f"Andra Markets <{user}>"
    msg["To"] = ", ".join(to)
    msg.set_content(TEMPLATE.format(
        li_caption=li_caption, tt_caption=tt_caption,
        tt_script=tt_script or "(not available)",
        characters=checks["characters"],
        limit_flag="" if checks["within_limit"] else "  <-- OVER LIMIT",
        hook=checks["hook"], hashtags=checks["hashtags"],
        audit="passed" if audit_ok else "FAILED",
        style_flags=", ".join(checks["style_flags"]) or "none",
        score=ctx["barometer"]["score"], label=ctx["barometer"]["label"],
        missing=missing, tiktok_count=tiktok_count))

    for path in attachments:
        p = Path(path)
        if not p.exists():
            continue
        kind, _ = mimetypes.guess_type(p.name)
        maj, _, sub = (kind or "application/octet-stream").partition("/")
        msg.add_attachment(p.read_bytes(), maintype=maj, subtype=sub, filename=p.name)

    _deliver(msg, host, port, user, pwd)


def _deliver(msg, host, port, user, pwd) -> None:
    if port == 465:
        with smtplib.SMTP_SSL(host, port) as s:
            s.login(user, pwd); s.send_message(msg)
    else:
        with smtplib.SMTP(host, port) as s:
            s.starttls(); s.login(user, pwd); s.send_message(msg)


WEEKLY = """{caption}

====================================================================
PRE-FLIGHT
Figure check: {audit}   Writing: {mode}
Sessions with no archived note: {missing}
Economic calendar: {calendar}

ATTACHMENTS
1. Weekly review, A4.
2. LinkedIn carousel. Upload as a Document post.
====================================================================
Generated by the Andra Markets close agent."""


def send_weekly(caption: str, attachments: list[str], week: str, headline: str,
                audit_ok: bool, mode: str, missing: list[str], calendar: bool) -> None:
    """The weekly review, ready to publish: caption first, then pre-flight."""
    host = os.getenv("SMTP_HOST", "smtp.gmail.com")
    port = int(os.getenv("SMTP_PORT", "465"))
    user, pwd = os.environ["SMTP_USER"], os.environ["SMTP_PASSWORD"]
    to = [a.strip() for a in os.environ["MAIL_TO"].split(",") if a.strip()]
    msg = EmailMessage()
    msg["Subject"] = (f"Andra Markets / Weekly / {week} / {headline[:70]}"
                      f"{'' if audit_ok else ' [REVIEW: figure check]'}")
    msg["From"] = f"Andra Markets <{user}>"
    msg["To"] = ", ".join(to)
    msg.set_content(WEEKLY.format(caption=caption, audit="passed" if audit_ok else "FAILED",
                                  mode=mode, missing=", ".join(missing) or "none",
                                  calendar="read" if calendar else "unavailable"))
    for path in attachments:
        p = Path(path)
        if p.exists():
            msg.add_attachment(p.read_bytes(), maintype="application", subtype="pdf",
                               filename=p.name)
    _deliver(msg, host, port, user, pwd)
